'use client';

import { useEffect, useRef, useState } from 'react';
import { ShieldCheck, RefreshCw, X, ArrowRight } from 'lucide-react';
import { useAuth } from '@/lib/contexts/AuthContext';

export default function OtpModal({ isOpen, onClose, email, onVerifySuccess }) {
  const [otp, setOtp] = useState(['', '', '', '', '', '']);
  const [isVerifying, setIsVerifying] = useState(false);
  const [error, setError] = useState('');
  const inputRefs = useRef([]);
  const { verifyMfa } = useAuth();

  useEffect(() => {
    if (isOpen) {
      setOtp(['', '', '', '', '', '']);
      setError('');
      inputRefs.current[0]?.focus();
    }
  }, [isOpen]);

  if (!isOpen) return null;

  const handleChange = (index, value) => {
    const digit = value.replace(/\D/g, '').slice(-1);
    const next = [...otp];
    next[index] = digit;
    setOtp(next);
    if (digit && index < 5) inputRefs.current[index + 1]?.focus();
  };

  const handleKeyDown = (index, event) => {
    if (event.key === 'Backspace' && !otp[index] && index > 0) inputRefs.current[index - 1]?.focus();
  };

  const handlePaste = (event) => {
    const digits = event.clipboardData.getData('text').replace(/\D/g, '').slice(0, 6).split('');
    if (!digits.length) return;
    event.preventDefault();
    setOtp([...digits, ...Array(6 - digits.length).fill('')]);
    inputRefs.current[Math.min(digits.length, 5)]?.focus();
  };

  const handleVerify = async (event) => {
    event.preventDefault();
    const code = otp.join('');
    if (code.length !== 6) {
      setError('Enter the complete six-digit authenticator code.');
      return;
    }
    setIsVerifying(true);
    setError('');
    try {
      await verifyMfa(code);
      onVerifySuccess();
    } catch (err) {
      setError(err.message || 'That code could not be verified. Try again.');
    } finally {
      setIsVerifying(false);
    }
  };

  return (
    <div className="fixed inset-0 z-[100] flex items-center justify-center bg-[#14251d]/65 p-4 backdrop-blur-sm" role="dialog" aria-modal="true" aria-labelledby="mfa-title">
      <div className="relative w-full max-w-md border border-[#e5e4dc] bg-[#fffefa] p-7 shadow-2xl sm:p-9">
        <button type="button" onClick={onClose} aria-label="Close verification" className="absolute right-4 top-4 grid h-9 w-9 place-items-center text-[#8b948b] hover:bg-[#f0f0e9]"><X size={18} /></button>
        <div className="mx-auto grid h-14 w-14 place-items-center rounded-full bg-[#e8eee7] text-[#315b49]"><ShieldCheck size={25} /></div>
        <div className="mt-5 text-center">
          <p className="editorial-kicker">Additional verification</p>
          <h2 id="mfa-title" className="mt-2 font-serif text-3xl text-[#1c2924]">Confirm it’s you.</h2>
          <p className="mx-auto mt-3 max-w-xs text-xs leading-6 text-[#788078]">Enter the six-digit code from your authenticator app for <strong className="text-[#43534a]">{email}</strong>.</p>
        </div>
        <form onSubmit={handleVerify} className="mt-7 space-y-5">
          <div className="flex justify-center gap-2" onPaste={handlePaste}>
            {otp.map((digit, index) => <input key={index} ref={(element) => { inputRefs.current[index] = element; }} type="text" inputMode="numeric" autoComplete="one-time-code" aria-label={`Verification digit ${index + 1}`} maxLength={1} value={digit} onChange={(event) => handleChange(index, event.target.value)} onKeyDown={(event) => handleKeyDown(index, event)} className="h-12 w-11 border border-[#d9ddd4] bg-white text-center text-lg font-semibold text-[#1c2924] outline-none focus:border-[#668775] focus:ring-2 focus:ring-[#668775]/15 sm:h-14 sm:w-12" />)}
          </div>
          {error && <p role="alert" className="text-center text-xs text-[#a34e43]">{error}</p>}
          <button type="submit" disabled={isVerifying} className="flex h-12 w-full items-center justify-between bg-[#315b49] px-5 text-xs font-semibold text-white hover:bg-[#214635] disabled:opacity-60">
            {isVerifying ? 'Verifying code…' : 'Verify and continue'} {isVerifying ? <RefreshCw size={15} className="animate-spin" /> : <ArrowRight size={15} />}
          </button>
        </form>
        <p className="mt-5 text-center text-[10px] leading-5 text-[#929990]">This code is generated by your authenticator app. It is not sent by email.</p>
      </div>
    </div>
  );
}